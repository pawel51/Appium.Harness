namespace Appium.Harness;

/// <summary>Direction a finger travels during a swipe.</summary>
public enum SwipeDirection
{
    /// <summary>Finger moves up; content below is revealed.</summary>
    Up,

    /// <summary>Finger moves down; content above is revealed.</summary>
    Down,

    /// <summary>Finger moves left; content to the right is revealed.</summary>
    Left,

    /// <summary>Finger moves right; content to the left is revealed.</summary>
    Right
}
